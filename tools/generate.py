"""Generate registers.py, alarms.py and translation files from tools/spec.py.

Usage:  python3 tools/generate.py
"""
from __future__ import annotations

import json
import pprint
from pathlib import Path

import alarm_texts
import spec

ROOT = Path(__file__).resolve().parent.parent
COMP = ROOT / "custom_components" / "kronoterm_ksm"
ALARM_SOURCE = ROOT / "tools" / "alarm_source.json"
LANGS = ("en", "uk", "sl")

HEADER = '"""GENERATED by tools/generate.py from tools/spec.py - do not edit by hand."""\n'


def _py(obj) -> str:
    return pprint.pformat(obj, width=110, sort_dicts=False)


def build_registers() -> str:
    sensors = [dict(key=k, address=a, kind=kind, **o) for k, a, kind, o, *_ in spec.SENSORS]
    enums = [
        dict(key=k, address=a, states=st, **o)
        for k, a, st, o, *_ in spec.ENUMS
    ]
    binaries = [dict(key=k, address=a, mask=m, **o) for k, a, m, o, *_ in spec.BINARY]
    selects = [dict(key=k, address=a, **o) for k, a, o, *_ in spec.SELECTS]
    switches = [dict(key=k, address=a, **o) for k, a, o, *_ in spec.SWITCHES]
    numbers = [dict(key=k, address=a, **o) for k, a, o, *_ in spec.NUMBERS]
    out = [HEADER, "from __future__ import annotations\n"]
    for name, data in (
        ("SENSORS", sensors),
        ("ENUM_SENSORS", enums),
        ("BINARY_SENSORS", binaries),
        ("SELECTS", selects),
        ("SWITCHES", switches),
        ("NUMBERS", numbers),
    ):
        out.append(f"{name}: list[dict] = {_py(data)}\n")
    return "\n".join(out)


def build_alarms() -> str:
    # tools/alarm_source.json: alarm bits with the Slovenian texts from the Kronoterm
    # CNS documentation; "register" is the documentation number (address = number - 1)
    source = json.loads(ALARM_SOURCE.read_text(encoding="utf-8"))
    texts: list[str] = []
    bits = []
    for item in source:
        text = item["sl"]
        if text not in texts:
            texts.append(text)
        bits.append((item["register"] - 1, int(item["mask"], 16), item["alarm"], texts.index(text)))
    if not (len(texts) == len(alarm_texts.EN) == len(alarm_texts.UK)):
        raise SystemExit(
            f"alarm text count mismatch: sl={len(texts)} en={len(alarm_texts.EN)} uk={len(alarm_texts.UK)}"
        )
    regs = sorted({b[0] for b in bits})
    return "\n".join(
        [
            HEADER,
            "from __future__ import annotations\n",
            "# (address, bitmask, is_alarm (False = warning), text index)",
            f"BITS: list[tuple[int, int, bool, int]] = {_py(bits)}\n",
            f"REGISTERS: list[int] = {_py(regs)}\n",
            "TEXTS: dict[str, list[str]] = {",
            f'    "sl": {_py(texts)},',
            f'    "en": {_py(alarm_texts.EN)},',
            f'    "uk": {_py(alarm_texts.UK)},',
            "}\n",
        ]
    )


def entity_translations(lang: str) -> dict:
    i = LANGS.index(lang)
    ent: dict[str, dict] = {p: {} for p in ("sensor", "binary_sensor", "select", "switch", "number", "button", "climate")}
    for k, _a, _kind, _o, *names in spec.SENSORS:
        ent["sensor"][k] = {"name": names[i]}
    for k, _a, _st, _o, names, states in spec.ENUMS:
        ent["sensor"][k] = {"name": names[i], "state": {s: v[i] for s, v in states.items()}}
    for k, _a, _m, _o, *names in spec.BINARY:
        ent["binary_sensor"][k] = {"name": names[i]}
    for k, _a, _o, names, states in spec.SELECTS:
        ent["select"][k] = {"name": names[i], "state": {s: v[i] for s, v in states.items()}}
    for k, _a, _o, *names in spec.SWITCHES:
        ent["switch"][k] = {"name": names[i]}
    for k, _a, _o, *names in spec.NUMBERS:
        ent["number"][k] = {"name": names[i]}
    for platform, items in spec.LOCAL.items():
        for k, names in items.items():
            ent[platform][k] = {"name": names[i]}
    return ent


def build_translations() -> None:
    base = json.loads((ROOT / "tools" / "translations_base.json").read_text(encoding="utf-8"))
    (COMP / "translations").mkdir(parents=True, exist_ok=True)
    for lang in LANGS:
        data = dict(base[lang])
        data["entity"] = entity_translations(lang)
        text = json.dumps(data, ensure_ascii=False, indent=2) + "\n"
        (COMP / "translations" / f"{lang}.json").write_text(text, encoding="utf-8")
        if lang == "en":
            (COMP / "strings.json").write_text(text, encoding="utf-8")


def main() -> None:
    COMP.mkdir(parents=True, exist_ok=True)
    (COMP / "registers.py").write_text(build_registers(), encoding="utf-8")
    (COMP / "alarms.py").write_text(build_alarms(), encoding="utf-8")
    build_translations()
    print("generated registers.py, alarms.py, strings.json, translations/{en,uk,sl}.json")


if __name__ == "__main__":
    main()
